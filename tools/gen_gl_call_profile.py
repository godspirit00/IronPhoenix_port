"""Generate src/nv2a/compat/gl_call_profile.gen.c: timing wrappers for every glad GL entry point.

Diagnostic only. With XB_GL_CALL_PROFILE=1 the wrappers are installed over glad's function
pointers and record per-function call counts and time on the renderer thread (the thread that
calls nv2a_gl_call_profile_set_thread). A "gl calls:" log line lists the top functions every 2 s.
Run: python tools/gen_gl_call_profile.py
"""
import re
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
hdr = (root / 'third_party/glad/include/glad/gl.h').read_text(encoding='utf-8')

protos = {}
for m in re.finditer(r'typedef[ \t]+([^;\n(]+?)[ \t]*\(GLAD_API_PTR \*(PFNGL\w+PROC)\)\(([^;]*?)\);', hdr):
    protos[m.group(2)] = (m.group(1).strip(), ' '.join(m.group(3).split()))
funcs = []
for m in re.finditer(r'GLAD_API_CALL (PFNGL\w+PROC) glad_gl(\w+);', hdr):
    if m.group(1) in protos:
        funcs.append((m.group(2), m.group(1)) + protos[m.group(1)])


def arg_names(args):
    if args in ('void', ''):
        return []
    out = []
    for a in args.split(','):
        ids = re.findall(r'[A-Za-z_]\w*', a)
        out.append(ids[-1])
    return out


o = ['/* Generated by tools/gen_gl_call_profile.py - do not edit. */',
     '#include "gl_call_profile.h"', '']
for i, (name, pfn, ret, args) in enumerate(funcs):
    names = arg_names(args)
    call = 'real_%s(%s)' % (name, ', '.join(names))
    o.append('static %s real_%s;' % (pfn, name))
    o.append('static %s GLAD_API_PTR w_%s(%s) {' % (ret, name, args))
    o.append('    int64_t t = glcp_begin();')
    if ret == 'void':
        o.append('    %s;' % call)
        o.append('    glcp_end(%d, t);' % i)
    else:
        o.append('    %s r = %s;' % (ret, call))
        o.append('    glcp_end(%d, t);' % i)
        o.append('    return r;')
    o.append('}')
o.append('')
o.append('const char *const glcp_names[%d] = {' % len(funcs))
o += ['    "gl%s",' % f[0] for f in funcs]
o.append('};')
o.append('const int glcp_count = %d;' % len(funcs))
o.append('')
o.append('void glcp_install_wrappers(void)')
o.append('{')
for name, *_ in funcs:
    o.append('    if (glad_gl%s && !real_%s) { real_%s = glad_gl%s; glad_gl%s = w_%s; }' % ((name,) * 6))
o.append('}')
(root / 'src/nv2a/compat/gl_call_profile.gen.c').write_text('\n'.join(o) + '\n', encoding='utf-8')
print('%d GL functions' % len(funcs))
