"""Generate src/symbols.gen.h from XbSymbolDatabase CLI output."""
import re
out = ['// GENERATED by tools/gen_symbols.py from notes/symbols_raw.txt', '#pragma once', '']
seen = set()
for line in open('notes/symbols_raw.txt'):
    m = re.match(r'(\w+?)__(FUN|VAR)__(?:(\w+?)__)?(\w+?)(\(.*\))? = (0x[0-9a-f]+)', line.strip())
    if not m: continue
    lib, kind, cc, name, args, addr = m.groups()
    if kind == 'VAR':
        name = name  # e.g. D3D_g_pDevice
    key = f'{lib}_{name}'
    if key in seen: continue
    seen.add(key)
    out.append(f'#define SYM_{lib}_{name} {addr}u{"  // " + (cc or "") + (args or "") if kind == "FUN" else ""}')
open('src/symbols.gen.h', 'w').write('\n'.join(out) + '\n')
print(len(seen))
