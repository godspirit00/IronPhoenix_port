"""Generate src/kernel/ktable.gen.cpp: kernel thunk table + weak logging stubs."""
import json, re
sigs = json.load(open('notes/kernel_sigs.json'))
# Corrections to the Cxbx header data
sigs['46'] = dict(name='HalReadWritePCISpace', kind='func', ret='void', cc='NTAPI', args=['a'] * 6)
sigs['323'] = dict(name='XboxHDKey', kind='var', type='XBOX_KEY_DATA')
sigs['325'] = dict(name='XboxSignatureKey', kind='var', type='XBOX_KEY_DATA')
sigs['354'] = dict(name='XboxAlternateSignatureKeys', kind='var', type='XBOX_KEY_DATA')
sigs['355'] = dict(name='XePublicKeyData', kind='var', type='UCHAR[]')
sigs['100'] = dict(name='KeDisconnectInterrupt', kind='func', ret='boolean_xt', cc='NTAPI', args=['a'])
imps = [int(x) for x in open('notes/xbe_info.txt').read().split('kernel imports (145):')[1].split()]

def nslots(arg):
    a = re.sub(r'\b(IN|OUT|OPTIONAL)\b', '', arg).strip()
    if re.match(r'^(LARGE_INTEGER|ULONGLONG|LONGLONG|ULARGE_INTEGER)\b', a):
        return 2
    return 1

lines = ['// GENERATED by tools/gen_kernel_table.py -- do not edit', '#include "kernel.h"', '']
table = []
for o in imps:
    s = sigs[str(o)]
    n = s['name']
    if s['kind'] == 'var':
        lines.append(f'extern "C" uint8_t xv_{n}[];')
        table.append(f'    {{{o}, "{n}", (void *)xv_{n}}},')
        continue
    cc = s['cc']
    if cc == '_cdecl':
        lines.append(f'extern "C" __attribute__((weak, cdecl)) uint32_t xk_{n}(const char *fmt, ...) {{ kstub_log({o}, "{n}", 0, nullptr); return 0; }}')
    else:
        slots = sum(nslots(a) for a in s['args'] if a != '...')
        attr = 'fastcall' if cc == 'FASTCALL' else 'stdcall'
        params = ', '.join(f'uint32_t a{i}' for i in range(slots)) or 'void'
        argv = ', '.join(f'a{i}' for i in range(slots))
        ntstatus = 'ntstatus' in s['ret'].lower() or 'NTSTATUS' in s['ret']
        rv = '0xC0000002u' if ntstatus else '0'
        if slots:
            body = f'uint32_t v[] = {{{argv}}}; kstub_log({o}, "{n}", {slots}, v);'
        else:
            body = f'kstub_log({o}, "{n}", 0, nullptr);'
        lines.append(f'extern "C" __attribute__((weak, {attr})) uint32_t xk_{n}({params}) {{ {body} return {rv}; }}')
    table.append(f'    {{{o}, "{n}", (void *)xk_{n}}},')
lines += ['', 'const KernelExport g_kernel_exports[] = {'] + table + ['    {0, nullptr, nullptr},', '};']
open('src/kernel/ktable.gen.cpp', 'w').write('\n'.join(lines) + '\n')
# Also emit a prototype header so implementations get the right signatures
hdr = ['// GENERATED -- prototypes of implemented-able kernel exports (all args as uint32_t slots)', '#pragma once', '#include <stdint.h>']
open('src/kernel/kprotos.gen.h', 'w').write('\n'.join(hdr) + '\n')
print('ok', len(table))
